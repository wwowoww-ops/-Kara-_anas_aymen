// ============================================================
// اختيار عشوائي
// ============================================================

function randomDua() {

    return DUAS[
        Math.floor(
            Math.random() *
            DUAS.length
        )
    ];
}

// ============================================================
// الوقت الحالي بتوقيت تونس
// ============================================================

function getTunisHour() {

    const hour =
        new Intl.DateTimeFormat(
            "en-US",
            {
                timeZone: TIMEZONE,
                hour: "numeric",
                hour12: false
            }
        ).format(
            new Date()
        );

    return Number(hour);
}

// ============================================================
// هل الساعة مخصصة للأذكار؟
// ============================================================

function isAdhkarHour() {

    const hour =
        getTunisHour();

    return ADHKAR_HOURS.includes(
        hour
    );
}

// ============================================================
// معرفة المجموعات
// ============================================================

function getThreads() {

    const result = [];

    try {

        if (
            global.data &&
            Array.isArray(
                global.data.allThreadID
            )
        ) {

            for (
                const id of global.data.allThreadID
            ) {

                if (id) {

                    result.push(
                        String(id)
                    );

                }

            }

        }

        if (
            !result.length &&
            global.data &&
            global.data.threadInfo instanceof Map
        ) {

            for (
                const id of global.data.threadInfo.keys()
            ) {

                if (id) {

                    result.push(
                        String(id)
                    );

                }

            }

        }

    } catch (error) {

        console.error(
            "[ادعية] THREAD ERROR:",
            error.message
        );

    }

    return [
        ...new Set(result)
    ];
}

// ============================================================
// إرسال للمجموعات
// ============================================================

async function sendToGroups(
    api,
    message
) {

    const threads =
        getThreads();

    if (
        !threads.length
    ) {

        console.log(
            "[ادعية] لا توجد مجموعات"
        );

        return;
    }

    for (
        const threadID of threads
    ) {

        try {

            await new Promise(
                resolve => {

                    try {

                        api.sendMessage(
                            message,
                            threadID,
                            () => resolve()
                        );

                    } catch (error) {

                        console.error(
                            "[ادعية] SEND ERROR:",
                            error.message
                        );

                        resolve();
                    }

                }
            );

            await new Promise(
                resolve =>
                    setTimeout(
                        resolve,
                        500
                    )
            );

        } catch (error) {

            console.error(
                "[ادعية] ERROR:",
                error.message
            );

        }

    }
}

// ============================================================
// تشغيل الجدولة
// ============================================================

function startScheduler(api) {

    if (started) {
        return;
    }

    started = true;

    console.log(
        "[HINA DUA] تم تشغيل نظام الأدعية"
    );

    // ========================================================
    // كل ساعة
    // ========================================================

    cron.schedule(
        "0 * * * *",
        async () => {

            // ------------------------------------------------
            // إذا كانت الساعة تحتوي على ذكر
            // لا نرسل دعاء
            // ------------------------------------------------

            if (
                isAdhkarHour()
            ) {

                console.log(
                    "[ادعية] تم تجاهل الإرسال لأن هذه الساعة مخصصة للأذكار"
                );

                return;
            }

            // ------------------------------------------------
            // إرسال الدعاء
            // ------------------------------------------------

            const message =
`⌬ ━━ 𝗛𝗜𝗡𝗔 ━━ ⌬

🤲 دعاء الساعة

${randomDua()}

🤍 لا تنسوا الدعاء وذكر الله`;

            await sendToGroups(
                api,
                message
            );

        },
        {
            timezone: TIMEZONE
        }
    );
}

// ============================================================
// HANDLE EVENT
// ============================================================

module.exports.handleEvent =
async function ({
    api,
    event
}) {

    try {

        if (!api) {
            return;
        }

        startScheduler(api);

    } catch (error) {

        console.error(
            "[HINA DUA ERROR]",
            error
        );

    }

};