// ==================================================
// تشغيل الأمر
// ==================================================

module.exports.run = async function ({
    api,
    event
}) {

    return api.sendMessage(

        createQuestion(0),

        event.threadID,

        (error, info) => {

            if (error) {

                console.error(
                    "❌ خطأ في بدء اختبار النمط:",
                    error
                );

                return;
            }

            global.client.handleReply =
                global.client.handleReply || [];

            global.client.handleReply.push({

                name:
                    module.exports.config.name,

                messageID:
                    info.messageID,

                author:
                    String(event.senderID),

                type:
                    "MBTI",

                question:
                    0,

                scores: {

                    E: 0,
                    I: 0,

                    S: 0,
                    N: 0,

                    T: 0,
                    F: 0,

                    J: 0,
                    P: 0

                }

            });

        }

    );

};


// ==================================================
// استقبال الإجابات
// ==================================================

module.exports.handleReply = async function ({
    api,
    event,
    handleReply
}) {

    if (!handleReply) {
        return;
    }

    if (
        handleReply.type !==
        "MBTI"
    ) {
        return;
    }

    if (
        String(event.senderID) !==
        String(handleReply.author)
    ) {
        return;
    }

    const answer =
        String(event.body || "")
            .trim()
            .toLowerCase();


    // ==================================================
    // إلغاء الاختبار
    // ==================================================

    if (

        answer === "الغاء" ||

        answer === "إلغاء" ||

        answer === "نمط الغاء" ||

        answer === "نمط إلغاء" ||

        answer === ".نمط الغاء" ||

        answer === ".نمط إلغاء"

    ) {

        return api.sendMessage(

            "تم إلغاء اختبار الأنماط",

            event.threadID

        );

    }


    // ==================================================
    // التحقق من الإجابة
    // ==================================================

    if (
        answer !== "1" &&
        answer !== "2"
    ) {

        return api.sendMessage(

            "إجابة غير صحيحة\n\n" +
            "أرسل 1 أو 2 فقط",

            event.threadID

        );

    }


    const currentQuestion =
        questions[
            handleReply.question
        ];


    if (!currentQuestion) {
        return;
    }


    // ==================================================
    // تحديد الاختيار
    // ==================================================

    const selected =

        answer === "1"

            ? currentQuestion.options[0]

            : currentQuestion.options[1];


    handleReply.scores[
        selected[2]
    ]++;


    handleReply.question++;


    // ==================================================
    // نهاية الاختبار
    // ==================================================

    if (
        handleReply.question >=
        questions.length
    ) {

        const type =
            calculate(
                handleReply.scores
            );


        const result =
            results[type];


        return api.sendMessage(

            "╭───〔 نتيجة اختبار النمط 〕───╮\n\n" +

            "نمط شخصيتك\n\n" +

            "【 " +
            type +
            " 】\n" +

            "「 " +
            result.name +
            " 」\n\n" +

            result.description +

            "\n\n" +

            "النتائج التفصيلية\n\n" +

            "E : " +
            handleReply.scores.E +

            "    I : " +
            handleReply.scores.I +

            "\n" +

            "S : " +
            handleReply.scores.S +

            "    N : " +
            handleReply.scores.N +

            "\n" +

            "T : " +
            handleReply.scores.T +

            "    F : " +
            handleReply.scores.F +

            "\n" +

            "J : " +
            handleReply.scores.J +

            "    P : " +
            handleReply.scores.P +

            "\n\n" +

            "╰────────────────────╯",

            event.threadID

        );

    }


    // ==================================================
    // إرسال السؤال التالي
    // ==================================================

    return api.sendMessage(

        createQuestion(
            handleReply.question
        ),

        event.threadID,

        (error, info) => {

            if (error) {

                console.error(
                    "❌ خطأ في إرسال سؤال النمط:",
                    error
                );

                return;
            }

            handleReply.messageID =
                info.messageID;

        }

    );

};