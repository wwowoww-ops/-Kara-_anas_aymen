// ==================================================
// إنشاء رسالة السؤال
// ==================================================

function createQuestion(index) {

    const question = questions[index];

    return (
        "╭───〔 اختبار الأنماط 〕───╮\n\n" +

        "السؤال " +
        (index + 1) +
        " من " +
        questions.length +
        "\n\n" +

        question.question +

        "\n\n" +

        "1 ـ " +
        question.options[0][1] +

        "\n" +

        "2 ـ " +
        question.options[1][1] +

        "\n\n" +

        "أرسل 1 أو 2 فقط\n\n" +

        "╰────────────────────╯"
    );
}


// ==================================================
// حساب النمط
// ==================================================

function calculate(scores) {

    const first =
        scores.E >= scores.I
            ? "E"
            : "I";

    const second =
        scores.S >= scores.N
            ? "S"
            : "N";

    const third =
        scores.T >= scores.F
            ? "T"
            : "F";

    const fourth =
        scores.J >= scores.P
            ? "J"
            : "P";

    return (
        first +
        second +
        third +
        fourth
    );
}


